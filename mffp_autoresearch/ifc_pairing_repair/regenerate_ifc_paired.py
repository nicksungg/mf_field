#!/usr/bin/env python
"""Regenerate the two local IFC-protocol ladders (ifc_poisson, ifc_heat) with a
NESTED condition design, repairing the round-2 pairing defect.

The shipped ladders draw an independent condition set per fidelity rung
(measured 2026-08-03: 0 of the finer-rung rows appear at any coarser rung, both
datasets), so every hf-lf residual, LF-teacher, and copy-LF construction on
them is invalid (round-2 report §5 item 5; preflight `pairing` check class).

Both datasets are generated by the local solvers in
`mf_field/generate_all_datasets.py` (`_make_poisson`, `_make_heat` — ifc_heat's
condition ranges match `_make_heat.BOUNDS` exactly), so a faithful repaired
ladder is available: one shared condition pool, coarse rung keeps all rows,
finer rungs keep nested PREFIXES of the same pool.  Every row at rung k then
exists at every coarser rung, and row i of a truncated finer array pairs with
row i of every coarser array.

Counts replicate the shipped IFC protocol: train 100/50/20/5 at 8/16/32/64,
test 128 at 64 only.  Output layout matches `benchmark_42/core/<name>/`
(ifc_raw: train/fidelity_<F>/{Xs,ys}.npy + test/fidelity_64/).

This is a STAGED repair candidate: it does not touch benchmark_42/core.
Whether the repaired ladder replaces the shipped one on the round-3 panel is a
launch-ADR decision (round3/PROGRAM_NOTE.md §7.3).
"""
import argparse
import importlib.util
import json
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
GEN = REPO / "mf_field" / "generate_all_datasets.py"

LADDER = [8, 16, 32, 64]
TRAIN_COUNTS = {8: 100, 16: 50, 32: 20, 64: 5}
N_TEST = 128
SEED_TRAIN = 20260803
SEED_TEST = 20260804


def load_gen_module():
    spec = importlib.util.spec_from_file_location("generate_all_datasets", GEN)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(name, make, out_root):
    gen = make()
    out = Path(out_root) / name
    # one shared pool, solved at every rung; finer rungs keep nested prefixes
    pool = gen(LADDER, TRAIN_COUNTS[LADDER[0]], SEED_TRAIN)
    test = gen([LADDER[-1]], N_TEST, SEED_TEST)
    for level in LADDER:
        n = TRAIN_COUNTS[level]
        d = out / "train" / f"fidelity_{level}"
        d.mkdir(parents=True, exist_ok=True)
        X = pool[level]["X"][:n]
        Y = pool[level]["Y"][:n].reshape(n, level, level)
        np.save(d / "Xs.npy", X)
        np.save(d / "ys.npy", Y)
    d = out / "test" / f"fidelity_{LADDER[-1]}"
    d.mkdir(parents=True, exist_ok=True)
    np.save(d / "Xs.npy", test[LADDER[-1]]["X"])
    np.save(d / "ys.npy", test[LADDER[-1]]["Y"].reshape(N_TEST, LADDER[-1], LADDER[-1]))

    # pairing self-check: finer-rung rows must sit verbatim in every coarser rung
    report = {"name": name, "ladder": LADDER, "train_counts": TRAIN_COUNTS,
              "n_test": N_TEST, "seed_train": SEED_TRAIN, "seed_test": SEED_TEST,
              "pairing": {}}
    for i, fine in enumerate(LADDER[1:], 1):
        coarse = LADDER[i - 1]
        Xf = np.load(out / "train" / f"fidelity_{fine}" / "Xs.npy")
        Xc = np.load(out / "train" / f"fidelity_{coarse}" / "Xs.npy")
        ok = all(np.array_equal(Xf[j], Xc[j]) for j in range(len(Xf)))
        report["pairing"][f"{fine}_nested_in_{coarse}"] = bool(ok)
        if not ok:
            raise SystemExit(f"{name}: nesting broken {fine}->{coarse}")
    (out / "pairing_report.json").write_text(json.dumps(report, indent=2))
    print(f"{name}: nested ladder written to {out} (pairing verified)")
    return report


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out_root", default=str(REPO / "regen_2026-08-03" / "ifc_paired"))
    args = ap.parse_args()
    mod = load_gen_module()
    reports = [build("ifc_poisson", mod._make_poisson, args.out_root),
               build("ifc_heat", mod._make_heat, args.out_root)]
    summary = HERE / "regeneration_report.json"
    summary.write_text(json.dumps(reports, indent=2))
    print(f"summary -> {summary}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
